#!/usr/bin/env python3
"""Rebuild js/search-index.js from the headings on each page.
Run from the site folder after editing page content:  python3 tools/build-search-index.py
Classes and events are searched straight from js/data.js, so they don't need this."""
import re, json, html, pathlib

PAGES = {
    "index.html": "home", "call-for-artists.html": "call", "classes.html": "classes",
    "gallery.html": "gallery", "visit.html": "visit", "about.html": "about", "support.html": "donate",
}
root = pathlib.Path(__file__).resolve().parent.parent

def clean(t):
    t = re.sub(r'<span class="tag[^"]*"[^>]*>.*?</span>', "", t, flags=re.S)
    t = re.sub(r"<[^>]+>", " ", t)
    return re.sub(r"\s+", " ", html.unescape(t)).strip()

entries = []
for file, key in PAGES.items():
    src = (root / file).read_text(encoding="utf-8")
    body = src[src.index("<main"):src.index("</main>")]
    for m in re.finditer(r"<h([123])([^>]*)>(.*?)</h\1>", body, re.S):
        if 'class="sr"' in m.group(2):
            continue
        title = clean(m.group(3))
        if not title:
            continue
        after = body[m.end():m.end() + 900]
        nxt = re.search(r"<h[123]", after)
        if nxt:
            after = after[:nxt.start()]
        entries.append({"t": title, "p": key, "u": file, "d": clean(after)[:140]})

out = root / "js" / "search-index.js"
out.write_text("/* Generated by tools/build-search-index.py. Rebuild when pages change. */\nwindow.WATERMAN_PAGES = "
               + json.dumps(entries, ensure_ascii=False, indent=1) + ";\n", encoding="utf-8")
print(f"Wrote {len(entries)} entries to {out}")
